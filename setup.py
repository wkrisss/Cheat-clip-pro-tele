"""First-run setup for the open-source Telegram bot."""
from getpass import getpass
from pathlib import Path

ROOT = Path(__file__).parent
ENV = ROOT / "backend" / ".env"

def ask(label, secret=False):
    value = getpass(label + ": ") if secret else input(label + ": ")
    return value.strip()

existing = {}
if ENV.exists():
    for line in ENV.read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1); existing[k] = v

print("Cheat Clip Pro Telegram setup")
print("Setup asks only Telegram token. AI keys are configured later inside Telegram.")
values = {
    "TELEGRAM_BOT_TOKEN": ask("Telegram bot token", True),
    "BACKEND_URL": ask("Backend URL (optional)") or "http://127.0.0.1:8000",
    "TELEGRAM_ADMIN_IDS": existing.get("TELEGRAM_ADMIN_IDS", ""),
}
values = {k: (v or existing.get(k, "")) for k, v in values.items()}
ENV.parent.mkdir(parents=True, exist_ok=True)
ENV.write_text("# Generated by setup.py; never commit this file.\n" + "\n".join(f"{k}={v}" for k, v in values.items()) + "\n")
ENV.chmod(0o600)
print("Saved backend/.env. Start backend, then run ./start-bot.sh.")
print("Use /settings in Telegram to update AI/transcript keys later.")
